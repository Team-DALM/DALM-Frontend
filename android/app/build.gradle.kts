val dalmEnvironment = Properties().apply {
    val environmentFile = rootProject.file("../.env")

    if (!environmentFile.exists()) {
        throw GradleException("frontend/.env 파일이 없습니다.")
    }

    environmentFile.inputStream().use { load(it) }
}

